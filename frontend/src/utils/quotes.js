/** 날짜마다 같은 한마디가 나오도록 날짜 문자열로 시작 위치를 정한다. */
export function noteIndexForDate(dateString) {
  let hash = 0;
  for (const char of dateString) hash = (hash * 31 + char.charCodeAt(0)) % 997;
  return hash % DAILY_NOTES.length;
}
